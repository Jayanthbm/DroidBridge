    static func modifiers(from flags: NSEvent.ModifierFlags) -> UInt8 {
        var value: UInt8 = 0
        if flags.contains(.control) { value |= 1 << 0 }
        if flags.contains(.shift) { value |= 1 << 1 }
        if flags.contains(.option) { value |= 1 << 2 }
        // DroidBridge maps the Mac Command key to Android's Control key.
        if flags.contains(.command) { value |= 1 << 0 }
        return value
    }
